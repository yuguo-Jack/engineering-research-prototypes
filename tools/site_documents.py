"""Render repository Markdown and rewrite local links for an offline static site."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit, urlunsplit
import html
import os
import re

import markdown


GENERATED_MARKER = "<!-- Generated by tools/catalog.py; edit source documents or project metadata. -->"


def documentation_files(root):
    candidates = [root / name for name in ("README.md", "CONTRIBUTING.md", "LICENSE")]
    candidates += sorted((root / "docs").glob("*.md"))
    candidates += sorted((root / "_templates/project").glob("*.md"))
    candidates += sorted((root / "projects").glob("*/*.md"))
    return [path for path in candidates if path.is_file()]


def documentation_target(root, source):
    return root / "site/docs" / source.relative_to(root).with_suffix(".html")


class LocalLinks(HTMLParser):
    """Change actual URL attributes, leaving code samples and text untouched."""

    def __init__(self, root, source, destination, documents):
        super().__init__(convert_charrefs=False)
        self.root = root.resolve()
        self.source = source
        self.destination = destination
        self.documents = documents
        self.parts = []

    def rewrite_url(self, value):
        url = urlsplit(value)
        if url.scheme or url.netloc or not url.path:
            return value
        target = ((self.root / unquote(url.path).lstrip("/")) if url.path.startswith("/")
                  else self.source.parent / unquote(url.path)).resolve()
        if not target.is_relative_to(self.root):
            raise ValueError("Documentation link escapes repository: " + value)
        target = self.documents.get(target, target)
        relative = Path(os.path.relpath(target, self.destination.parent)).as_posix()
        return urlunsplit(("", "", quote(relative, safe="/.-_~"), url.query, url.fragment))

    def start(self, tag, attrs, closing):
        rendered = []
        for name, value in attrs:
            if value is None:
                rendered.append(name)
                continue
            if name in ("href", "src"):
                value = self.rewrite_url(value)
            rendered.append(f'{name}="{html.escape(value, quote=True)}"')
        self.parts.append("<" + tag + (" " + " ".join(rendered) if rendered else "") + closing)

    def handle_starttag(self, tag, attrs):
        self.start(tag, attrs, ">")

    def handle_startendtag(self, tag, attrs):
        self.start(tag, attrs, " />")

    def handle_endtag(self, tag):
        self.parts.append("</" + tag + ">")

    def handle_data(self, data):
        self.parts.append(data)

    def handle_entityref(self, name):
        self.parts.append("&" + name + ";")

    def handle_charref(self, name):
        self.parts.append("&#" + name + ";")

    def handle_comment(self, data):
        self.parts.append("<!--" + data + "-->")

    def handle_decl(self, declaration):
        self.parts.append("<!" + declaration + ">")

    def render(self, content):
        self.feed(content)
        self.close()
        return "".join(self.parts)


def add_documentation(root, config, files, shell):
    sources = documentation_files(root)
    documents = {source.resolve(): documentation_target(root, source) for source in sources}
    for source in sources:
        key = source.relative_to(root).as_posix()
        text = files.get(key, source.read_text(encoding="utf-8"))
        body = markdown.markdown(text, extensions=["tables", "fenced_code", "sane_lists", "toc"], output_format="html")
        heading = re.search(r"<h1(?:\s[^>]*)?>(.*?)</h1>", body, re.S)
        title = html.unescape(re.sub(r"<[^>]+>", "", heading.group(1))) if heading else source.stem
        destination = documents[source.resolve()]
        body = LocalLinks(root, source, destination, documents).render(body)
        prefix = "../" * len(destination.relative_to(root).parent.parts)
        guide = f'<section class="document-heading"><a class="back-link" href="{prefix}index.html">← 成果总览</a><p class="eyebrow">DOCUMENTATION</p><p class="document-path">{html.escape(key)}</p></section>'
        page = shell(title, guide + '<article class="document">' + body + "</article>", prefix, config=config)
        files[destination.relative_to(root).as_posix()] = page
    for key, content in list(files.items()):
        if key.endswith(".html"):
            destination = root / key
            files[key] = LocalLinks(root, destination, destination, documents).render(content)
    return files
